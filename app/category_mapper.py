def canonicalize(label: str) -> str:
    """Приводит ответ MiMo к каноническому названию категории.

    Возвращает пустую строку, если категорию не удалось распознать.
    """
    if not label:
        return ""
    stripped = label.strip()
    if stripped in CATEGORY_KEY_MAP:
        return stripped

    low = " ".join(stripped.lower().split())

    # 1) точное совпадение с алиасом
    for alias, canonical in ALIASES.items():
        if low == alias:
            return canonical

    # 2) подстрока (только для достаточно длинных алиасов, чтобы не ловить мусор)
    for alias, canonical in ALIASES.items():
        if len(alias) >= 4 and alias in low:
            return canonical

    # 3) каноническое имя как подстрока
    for canonical in CATEGORY_KEY_MAP:
        if canonical.lower() in low:
            return canonical

    return ""


def key_for(category: str) -> str:
    """Клавиша TagMe для канонической категории (пустая строка, если неизвестна)."""
    return CATEGORY_KEY_MAP.get(category, "")


def categories_list() -> list[str]:
    """Список канонических категорий в порядке, в котором они заданы."""
    return list(CATEGORY_KEY_MAP.keys())
